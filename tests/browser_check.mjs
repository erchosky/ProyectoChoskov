const ammoState=(await state()).player;const rounds=ammoState.loaded+ammoState.reserve;
await clickButton(b=>b.text.startsWith('SIGILO'));

check((await state()).crouched&&(await state()).player.loaded+(await state()).player.reserve===rounds,'mouse on stealth button toggles stance without shooting');
await page.keyboard.press('C');await page.waitForTimeout(100);
check(!(await state()).crouched,'keyboard restores standing stance');
