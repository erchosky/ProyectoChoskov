await clickButton(b=>b.text==='Ajustes');
await clickButton(b=>b.text==='Probar controles táctiles');
const labSession=await context.newCDPSession(page);
const lp=(id,x,y)=>({id,x,y,radiusX:8,radiusY:8,force:1});
