await labSession.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[lm,lr]});
await page.waitForTimeout(150);
// CDP touchEnd ends the contact set. DOM changedTouches represents a single lifted finger.
await page.evaluate(()=>{
 const canvas=document.querySelector('canvas');
 const t=(id,x,y)=>new Touch({identifier:id,target:canvas,clientX:x,clientY:y,pageX:x,pageY:y,screenX:x,screenY:y,radiusX:8,radiusY:8,force:1});
 const a=t(2,168,603),b=t(7,1130,545),c=t(19,640,578);
 const send=(type,touches,changed)=>canvas.dispatchEvent(new TouchEvent(type,{bubbles:true,cancelable:true,touches,targetTouches:touches,changedTouches:changed}));
 send('touchstart',[a,b,c],[c]);send('touchend',[a,b],[c]);
});
await page.waitForTimeout(150);
check((await state()).touch_test.combos===1&&(await state()).touch_test.fingers===2,'calibration accepts three simultaneous browser touch contacts');
await page.evaluate(()=>{
 const canvas=document.querySelector('canvas');
 const t=(id,x,y)=>new Touch({identifier:id,target:canvas,clientX:x,clientY:y,pageX:x,pageY:y,screenX:x,screenY:y});
 const a=t(2,168,603),b=t(7,1130,545);
 canvas.dispatchEvent(new TouchEvent('touchend',{bubbles:true,cancelable:true,touches:[b],targetTouches:[b],changedTouches:[a]}));
});
