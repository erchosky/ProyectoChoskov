check((await state()).touch_test.fingers===1&&(await state()).touch_test.move[0]===0&&(await state()).touch_test.aim[1]<0,'calibration releases only the lifted finger');
await page.screenshot({path:'builds/web-controles.png'});
await labSession.send('Input.dispatchTouchEvent',{type:'touchCancel',touchPoints:[]});
await page.waitForTimeout(100);
check((await state()).touch_test.fingers===0,'browser touch cancellation clears the remaining owner');
await clickButton(b=>b.text==='Volver a Ajustes');
check(!(await state()).touch_test,'closing calibration removes test contacts');
await clickButton(b=>b.text==='Volver');
await clickButton(b=>b.text==='Fabricar');
await page.screenshot({path:'builds/web-fabricar.png'});
check((await state()).mode==='shelter'&&(await state()).buttons.filter(b=>b.text.startsWith('Fabricar:')).length===5,'crafting tab presents five recipes');
await page.mouse.click(1090,650);
await page.waitForTimeout(500);
let s=await state();check(s.mode==='raid','footer starts native Godot raid');
const session=await context.newCDPSession(page);
const p=(id,x,y)=>({id,x,y,radiusX:8,radiusY:8,force:1});
const left=p(2,116,603),right=p(7,1130,600);
await session.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[left,right]});
const moved=p(2,168,603),aimed=p(7,1130,545);
await session.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[moved,aimed]});
await page.waitForTimeout(350);
let after=await state();check(after.player.x>s.player.x&&after.player.loaded<s.player.loaded&&after.controls.fingers===2,'browser sends simultaneous real movement/aim touches');
await page.evaluate(()=>{
 const canvas=document.querySelector('canvas');
 const t=(id,x,y)=>new Touch({identifier:id,target:canvas,clientX:x,clientY:y,pageX:x,pageY:y,screenX:x,screenY:y,radiusX:8,radiusY:8,force:1});
 const a=t(2,168,603),b=t(7,1130,545),c=t(19,870,443);
 canvas.dispatchEvent(new TouchEvent('touchstart',{bubbles:true,cancelable:true,touches:[a,b,c],targetTouches:[a,b,c],changedTouches:[c]}));
 canvas.dispatchEvent(new TouchEvent('touchend',{bubbles:true,cancelable:true,touches:[a,b],targetTouches:[a,b],changedTouches:[c]}));
});
await page.waitForTimeout(100);
after=await state();check(after.player.reload>0&&after.controls.fingers===2,'third finger reload works with both joysticks held');
await page.screenshot({path:'builds/web-multitouch.png'});
await session.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
await page.waitForTimeout(100);check((await state()).controls.fingers===0,'all browser touches release');
await page.keyboard.press('Tab');await page.waitForTimeout(150);
check((await state()).paused,'keyboard opens paused backpack');
await page.screenshot({path:'builds/web-mochila.png'});
